const { run } = require('./harness');

run('CRM / INVOICING / AUTOMATIONS / REPORTS / PLAN GATES', async ({ ok, call, db, O, ids: { tenantId } }) => {
  const sleepMs = (ms) => new Promise((r) => setTimeout(r, ms));
  console.log('CONTACTS / CSV');
  let r = await call('POST', '/contacts', { name: 'María Pérez', email: 'maria@example.com', phone: '+13055550100' });
  ok(r.status === 201, 'create contact', r); const contact = r.data;
  r = await call('POST', '/contacts/import', { rows: [{ name: 'Ana', email: 'ana@x.com', tags: 'vip;nuevo' }, { name: 'Dup', email: 'MARIA@example.com' }, { name: 'Bad', email: 'nope' }, { name: '=cmd()', phone: '305-555-1111' }] });
  ok(r.status === 201 && r.data.created === 2 && r.data.skippedDuplicates === 1 && r.data.invalid.length === 1, 'import: 2 created, 1 dup, 1 invalid', r.data);
  r = await call('GET', '/contacts/export', null, true);
  const csv = await r.text();
  ok(r.status === 200 && csv.includes("'=cmd()") && csv.includes('maria@example.com'), 'export csv + formula neutralised');

  console.log('PRODUCTS / QUOTE / INVOICE');
  r = await call('POST', '/products', { name: 'Diseño web', unitPriceCents: 150000, taxable: true });
  ok(r.status === 201, 'create product', r);
  r = await call('POST', '/sales-documents', { type: 'quote', contactId: contact._id, lines: [{ description: 'Diseño web', quantity: 1, unitPriceCents: 150000 }, { description: 'Hosting (exento)', quantity: 12, unitPriceCents: 1000, taxable: false }] });
  ok(r.status === 201 && /^QUO-0001$/.test(r.data.number), 'quote QUO-0001', r.data.number);
  // workspace tax 8.25% applied by default: taxable 1500 -> 123.75
  ok(r.data.taxCents === 12375 && r.data.totalCents === 150000 + 12000 + 12375, 'default workspace tax applied', r.data);
  const quote = r.data;
  r = await call('POST', `/sales-documents/${quote._id}/convert`, {});
  ok(r.status === 201 && /^SM-0001$/.test(r.data.number) && r.data.type === 'invoice', 'convert → invoice SM-0001 (custom prefix)', r.data.number);
  const invoice = r.data;
  r = await call('POST', `/sales-documents/${quote._id}/convert`, {});
  ok(r.status === 409, 'second conversion refused');
  r = await call('PUT', `/sales-documents/${invoice._id}`, { notes: 'Gracias', lines: [{ description: 'x', quantity: 1, unitPriceCents: 1 }] });
  ok(r.status === 200, 'draft invoice lines editable');
  r = await call('PUT', `/sales-documents/${invoice._id}`, { lines: [{ description: 'Diseño web', quantity: 1, unitPriceCents: 150000 }, { description: 'Hosting', quantity: 12, unitPriceCents: 1000, taxable: false }] });
  const total = r.data.totalCents;
  r = await call('POST', `/sales-documents/${invoice._id}/payments`, { amountCents: total + 1, method: 'zelle' });
  ok(r.status === 400, 'overpayment rejected');
  r = await call('POST', `/sales-documents/${invoice._id}/payments`, { amountCents: 50000, method: 'zelle', reference: 'ZL-1' });
  ok(r.data.status === 'partial' && r.data.balanceCents === total - 50000, 'partial payment', r.data.status);
  r = await call('PUT', `/sales-documents/${invoice._id}`, { lines: [{ description: 'hack', quantity: 1, unitPriceCents: 1 }] });
  ok(r.status === 400, 'amounts frozen after first payment');
  r = await call('POST', `/sales-documents/${invoice._id}/payments`, { amountCents: total - 50000, method: 'cash' });
  ok(r.data.status === 'paid' && r.data.balanceCents === 0, 'fully paid');
  r = await call('POST', `/sales-documents/${invoice._id}/payments`, { amountCents: 1, method: 'cash' });
  ok(r.status === 400, 'no payments on a paid invoice');
  const payId = (await call('GET', `/sales-documents/${invoice._id}`)).data.payments[0]._id;
  r = await call('DELETE', `/sales-documents/${invoice._id}/payments/${payId}`);
  ok(r.data.status === 'partial', 'deleting a payment re-opens the invoice', r.data.status);
  r = await call('POST', `/sales-documents/${invoice._id}/status`, { status: 'void' });
  ok(r.status === 400, 'cannot void an invoice with payments');
  r = await call('GET', `/sales-documents/${invoice._id}/pdf`, null, true);
  const pdf = Buffer.from(await r.arrayBuffer());
  ok(r.status === 200 && pdf.subarray(0, 5).toString() === '%PDF-' && /pdf/.test(r.headers.get('content-type')), 'PDF download', r.status);
  r = await call('POST', `/sales-documents/${invoice._id}/send`, {});
  ok(r.status === 400 && /email/i.test(JSON.stringify(r.json)), 'send without mailbox → clear message', r.json);
  r = await call('GET', '/sales-documents?status=partial');
  ok(Array.isArray(r.data) && r.data.length === 1, 'list filtered by status');

  console.log('DEAL → INVOICE closes deal');
  r = await call('POST', '/deals', { title: 'Proyecto web', value: 500, contactId: contact._id });
  ok(r.status === 201, 'create deal', r.json); const deal = r.data;
  r = await call('POST', `/sales-documents/from-deal/${deal._id}`, { type: 'invoice' });
  ok(r.status === 201 && r.data.totalCents === Math.round(50000 * 1.0825), 'invoice from deal', r.data.totalCents);
  const dealInv = r.data;
  r = await call('POST', `/sales-documents/${dealInv._id}/payments`, { amountCents: dealInv.totalCents, method: 'check' });
  ok(r.data.status === 'paid', 'deal invoice paid');
  const dealAfter = await db.collection('deals').findOne({ _id: O(deal._id) });
  ok(dealAfter.stage === 'closed_won', 'deal auto-closed as won', dealAfter.stage);

  console.log('TASKS / NOTES / TIMELINE / QUICK REPLIES');
  r = await call('POST', '/tasks', { title: 'Llamar a María', contactId: contact._id, dueAt: new Date(Date.now() + 3600e3).toISOString() });
  ok(r.status === 201, 'create task', r.json); const task = r.data;
  r = await call('PATCH', `/tasks/${task._id}`, { status: 'done' });
  ok(r.data.status === 'done' && r.data.completedAt, 'complete task');
  r = await call('POST', '/notes', { body: 'Prefiere WhatsApp', contactId: contact._id });
  ok(r.status === 201, 'create note');
  r = await call('POST', '/quick-replies', { shortcut: 'hola', body: 'Hola, ¿en qué te ayudo?' });
  ok(r.status === 201, 'create quick reply');
  r = await call('POST', '/quick-replies', { shortcut: 'hola', body: 'dup' });
  ok(r.status === 409, 'duplicate shortcut → 409');
  r = await call('POST', '/quick-replies', { shortcut: 'Bad Shortcut', body: 'x' });
  ok(r.status === 400, 'invalid shortcut rejected');
  r = await call('GET', `/activities/timeline?contactId=${contact._id}`);
  const types = new Set((r.data || []).map((i) => i.type));
  ok(['note', 'task', 'quote', 'invoice', 'payment', 'deal'].every((t) => types.has(t)), 'timeline merges notes/tasks/docs/payments/deals', [...types]);
  r = await call('GET', '/activities/tags');
  ok(Array.isArray(r.data) && r.data.includes('vip'), 'tags listing');

  console.log('AUTOMATIONS');
  const agent = (await call('GET', '/workspaces')).data;
  r = await call('POST', '/automations', { name: 'Nuevo lead → tag + tarea', trigger: 'lead.created', actions: [{ type: 'add_tag', config: { tag: 'caliente' } }, { type: 'create_task', config: { title: 'Dar seguimiento a {{contact.firstName}}', dueInHours: 24 } }, { type: 'send_webhook', config: { url: 'https://127.0.0.1/hook' } }, { type: 'update_status', config: { target: 'lead', status: 'contacted' } }] });
  ok(r.status === 201, 'create automation', r.json);
  r = await call('POST', '/leads', { title: 'Lead de prueba', contactId: contact._id });
  ok(r.status === 201, 'create lead (fires lead.created)', r.json); const lead = r.data;
  await sleepMs(1500);
  const c2 = await db.collection('contacts').findOne({ _id: O(contact._id) });
  ok((c2.tags || []).includes('caliente'), 'automation tagged the contact', c2.tags);
  const t2 = await db.collection('tasks').findOne({ tenantId, source: 'automation' });
  ok(t2 && t2.title === 'Dar seguimiento a María', 'automation created personalised task', t2 && t2.title);
  const l2 = await db.collection('leads').findOne({ _id: O(lead._id) });
  ok(l2.status === 'contacted', 'automation updated lead status', l2.status);
  r = await call('GET', '/automations/runs');
  const run = r.data[0];
  ok(run && run.status === 'partial' && run.results.length === 4 && run.results.filter((x) => x.ok).length === 3, 'run log: 3 ok + SSRF webhook blocked', run && run.results);
  ok(run.results.find((x) => x.type === 'send_webhook').detail.includes('público'), 'webhook to 127.0.0.1 refused');
  // contact.created + keywords conditions
  await call('POST', '/automations', { name: 'Contacto VIP', trigger: 'contact.created', conditions: { keywords: ['x'] }, actions: [{ type: 'add_tag', config: { tag: 'no' } }] });
  await call('POST', '/contacts', { name: 'Otro', email: 'otro@x.com' });
  await sleepMs(800);
  const c3 = await db.collection('contacts').findOne({ tenantId, email: 'otro@x.com' });
  ok(!(c3.tags || []).includes('no'), 'non-matching condition does not run');
  // deal stage
  await call('POST', '/automations', { name: 'Deal ganado', trigger: 'deal.stage_changed', conditions: { stage: 'negotiation' }, actions: [{ type: 'create_task', config: { title: 'Preparar contrato' } }] });
  r = await call('POST', '/deals', { title: 'D2', value: 10, contactId: contact._id });
  await call('PATCH', `/deals/${r.data._id}`, { stage: 'negotiation' });
  await sleepMs(800);
  ok(!!(await db.collection('tasks').findOne({ tenantId, title: 'Preparar contrato' })), 'deal stage change triggers automation');

  console.log('REPORTS');
  r = await call('GET', '/reports/overview');
  ok(r.status === 200 && r.data.funnel.contacts >= 3 && r.data.sales[0] && r.data.sales[0].collectedCents > 0, 'overview has funnel + sales', r.data.sales);
  r = await call('GET', '/reports/overview?from=2020-01-01&to=2026-01-01');
  ok(r.status === 400, 'oversized range rejected');

  console.log('PLAN GATES / READ-ONLY');
  await db.collection('tenants').updateOne({ _id: tenantId }, { $set: { plan: 'starter', subscription: { planKey: 'starter', status: 'active', provider: 'manual', complimentary: true } } });
  r = await call('GET', '/deals');
  ok(r.status === 403 && r.json.code === 'PLAN_LIMIT_REACHED', 'starter: deals blocked', r.json);
  r = await call('GET', '/sales-documents');
  ok(r.status === 200, 'starter: invoicing allowed');
  await db.collection('tenants').updateOne({ _id: tenantId }, { $set: { plan: 'free', subscription: { planKey: 'free', status: 'active', provider: 'manual' } } });
  r = await call('GET', '/sales-documents');
  ok(r.status === 403, 'free: invoicing blocked');
  r = await call('POST', '/automations', { name: 'x', trigger: 'lead.created', actions: [{ type: 'add_tag', config: { tag: 'a' } }] });
  ok(r.status === 403, 'free: cannot create automations (limit 0)', r.status);
  await db.collection('tenants').updateOne({ _id: tenantId }, { $set: { plan: 'pro', status: 'trial', trialEndsAt: new Date(Date.now() - 86400e3), subscription: { planKey: 'pro', status: 'trialing', provider: 'manual' } } });
  r = await call('POST', '/contacts', { name: 'Bloqueado' });
  ok(r.status === 402 && r.json.code === 'SUBSCRIPTION_REQUIRED', 'expired trial: writes → 402', r.json);
  r = await call('GET', '/contacts');
  ok(r.status === 200, 'expired trial: reads still work');
  const before = await db.collection('automationruns').countDocuments({ tenantId });
  await call('POST', '/leads', { title: 'Sin pagar', contactId: contact._id }).catch(() => {});
  await sleepMs(800);
  ok((await db.collection('automationruns').countDocuments({ tenantId })) === before, 'read-only accounts do not run automations');

});
